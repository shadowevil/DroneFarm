function moveDoc(name, dirDesc) {
  return [
    `\`\`\`${name}()\`\`\``,
    `Flies the drone one tile ${dirDesc}.`,
    '',
    'At the map edge the drone wraps around to the opposite side of the world.',
    '',
    '| | |',
    '| Parameters | none |',
    '| Returns | nothing |',
    '| Duration | one glide (speed multiplier applies) |',
  ].join('\n');
}

